"""Rebuild the embedded Windows x64 LZMA decoder using MSVC's bundled Clang."""
from pathlib import Path
import os
import struct
import subprocess

root = Path(__file__).resolve().parent.parent
tools = Path(os.environ["ProgramFiles"]) / "Microsoft Visual Studio"
vcvars = next(tools.glob("*/*/VC/Auxiliary/Build/vcvars64.bat"))
vc = vcvars.parents[2]
clang = vc / "Tools/Llvm/x64/bin/clang-cl.exe"
linker = vc / "Tools/Llvm/x64/bin/lld-link.exe"
folder = root / "target/section-decoder"
folder.mkdir(exist_ok=True)
obj = folder / "decoder.obj"
image = folder / "decoder.exe"
compile_args = [str(clang), "/nologo", "/c", "/O1", "/GS-", "/Zl",
                "/clang:-Oz", "/clang:-ffreestanding", "/clang:-fno-builtin",
                "/clang:-fno-jump-tables", "/clang:-ffunction-sections",
                "/clang:-funwind-tables",
                str(root / "src/compression/decoder.c"), "/Fo" + str(obj)]
link_args = [str(linker), "/entry:section_init", "/subsystem:console",
             "/nodefaultlib", "/fixed", "/dynamicbase:no", "/opt:ref",
             "/merge:.rdata=.text",
             "/out:" + str(image), str(obj)]
command = (f'call "{vcvars}" >nul && ' + subprocess.list2cmdline(compile_args)
           + " && " + subprocess.list2cmdline(link_args))
batch = folder / "build.cmd"
batch.write_text("@echo off\n" + command + "\n", encoding="utf-8")
subprocess.run([os.environ["ComSpec"], "/d", "/c", str(batch)], check=True)

data = image.read_bytes()
pe = struct.unpack_from("<I", data, 0x3C)[0]
opt = pe + 24
table = opt + struct.unpack_from("<H", data, pe + 20)[0]
sections = {}
for i in range(struct.unpack_from("<H", data, pe + 6)[0]):
    at = table + 40 * i
    name = data[at:at + 8].rstrip(b"\0")
    sections[name] = struct.unpack_from("<IIII", data, at + 8)
size, base, raw_size, raw = sections[b".text"]
code = data[raw:raw + size]
assert struct.unpack_from("<II", data, opt + 112 + 8) == (0, 0), "unexpected imports"
assert struct.unpack_from("<II", data, opt + 112 + 40) == (0, 0), "unexpected base fixups"
config_offset = code.index(b"SBINIT01")
entry = struct.unpack_from("<I", data, opt + 16)[0] - base
unwind_size, _, _, unwind_raw = sections[b".pdata"]
entries = []
for at in range(unwind_raw, unwind_raw + unwind_size, 12):
    begin, end, unwind = struct.unpack_from("<III", data, at)
    assert base <= begin < end <= base + size
    assert base <= unwind < base + size and code[unwind - base] >> 3 == 0
    entries.append((begin - base, end - base, unwind - base))

destination = root / "src/compression"
(destination / "decoder.bin").write_bytes(code)
metadata = ["// Generated by scripts/build_section_decoder.py.",
            f"pub const ENTRY_OFFSET: u32 = {entry};",
            f"pub const CONFIG_OFFSET: usize = {config_offset};",
            "pub const RUNTIME_FUNCTIONS: &[(u32, u32, u32)] = &["]
metadata.extend(f"    ({begin}, {end}, {unwind})," for begin, end, unwind in entries)
metadata.append("];\n")
(destination / "decoder.rs").write_text("\n".join(metadata), encoding="utf-8")
print(f"Embedded {len(code)} decoder bytes and {len(entries)} runtime entries")
